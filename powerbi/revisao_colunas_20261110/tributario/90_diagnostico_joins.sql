-- DIAGNÓSTICO SOMENTE LEITURA. Não executado nesta revisão.
-- Uma chamada por empresa para MES_INICIO..MES_FIM, antes dos candidatos.
-- Zero grupos problemáticos é necessário, mas não prova correção de totais/unidades.
-- Resultados >0 exigem examinar as chaves e vigências, não deduplicar com MAX.
-- Cadastro é checado nas chaves presentes em FATURAMENTO do intervalo; alguns
-- grupos podem ser irrelevantes a um relatório específico e devem ser investigados.
WITH FAT AS (
    SELECT MES_COMPETENCIA, MES_REFERENCIA, DOCUMENTO_IMPRESSAO, DOCUMENTO_CALCULO,
           INSTALACAO, CONTA_CONTRATO, PARCEIRO_NEGOCIO, TIPO_CALCULO, SUBCLASSE, ESTORNO_PLENO
    FROM EQTLINFO_PRD.{SCHEMA}.FATURAMENTO
    WHERE MES_COMPETENCIA BETWEEN '{MES_INICIO}' AND '{MES_FIM}'
), ELEGIVEIS AS (
    SELECT MES_COMPETENCIA, DOCUMENTO_IMPRESSAO, DOCUMENTO_CALCULO
    FROM EQTLINFO_PRD.{SCHEMA}.ITENS_FATURAMENTO
    WHERE MES_COMPETENCIA BETWEEN '{MES_INICIO}' AND '{MES_FIM}'
      AND (ITEM_DOCUMENTO IN ('ZENCOV','ZESCAS') OR OPERACAO='0153'
           OR (OPERACAO IN ('0100','0200','0300') AND SUB_OPERACAO IN ('0016','0026','0010')))
    GROUP BY MES_COMPETENCIA, DOCUMENTO_IMPRESSAO, DOCUMENTO_CALCULO
), CONSUMO AS (
    SELECT MES_COMPETENCIA, MES_REFERENCIA, DOCUMENTO_IMPRESSAO, DOCUMENTO_CALCULO,
           INSTALACAO, CONTA_CONTRATO, PARCEIRO_NEGOCIO
    FROM FAT
    WHERE TIPO_CALCULO IN ('CP','CF') AND SUBSTR(SUBCLASSE,1,2)='CP' AND ESTORNO_PLENO IS NULL
)
SELECT 'FATURAMENTO: mais de um cabeçalho por mês/impressão/cálculo' AS "Teste",
       COUNT(*) AS "GruposProblematicos"
FROM (
    SELECT MES_COMPETENCIA,DOCUMENTO_IMPRESSAO,DOCUMENTO_CALCULO
    FROM FAT
    GROUP BY MES_COMPETENCIA,DOCUMENTO_IMPRESSAO,DOCUMENTO_CALCULO
    HAVING COUNT(*)>1
)
UNION ALL
SELECT 'Itens elegíveis: chave documental nula', COUNT(*)
FROM ELEGIVEIS
WHERE MES_COMPETENCIA IS NULL OR DOCUMENTO_IMPRESSAO IS NULL OR DOCUMENTO_CALCULO IS NULL
UNION ALL
SELECT 'Itens elegíveis: sem cabeçalho na chave completa', COUNT(*)
FROM ELEGIVEIS I
WHERE NOT EXISTS (
    SELECT 1 FROM FAT B WHERE I.MES_COMPETENCIA=B.MES_COMPETENCIA
      AND I.DOCUMENTO_IMPRESSAO=B.DOCUMENTO_IMPRESSAO AND I.DOCUMENTO_CALCULO=B.DOCUMENTO_CALCULO
)
UNION ALL
SELECT 'TAB_PARCEIRO_NEGOCIO: mais de uma linha por parceiro usado', COUNT(*)
FROM (
    SELECT P.PARCEIRO_NEGOCIO
    FROM EQTLINFO_PRD.{SCHEMA}.TAB_PARCEIRO_NEGOCIO P
    WHERE EXISTS (SELECT 1 FROM FAT B WHERE B.PARCEIRO_NEGOCIO=P.PARCEIRO_NEGOCIO)
    GROUP BY P.PARCEIRO_NEGOCIO HAVING COUNT(*)>1
)
UNION ALL
SELECT 'TAB_CADASTRO: mais de uma linha por instalação usada (Injetada)', COUNT(*)
FROM (
    SELECT D.INSTALACAO
    FROM EQTLINFO_PRD.{SCHEMA}.TAB_CADASTRO D
    WHERE EXISTS (SELECT 1 FROM FAT B WHERE B.INSTALACAO=D.INSTALACAO)
    GROUP BY D.INSTALACAO HAVING COUNT(*)>1
)
UNION ALL
SELECT 'TAB_CADASTRO: mais de uma linha por instalação/conta usada (Isenção)', COUNT(*)
FROM (
    SELECT D.INSTALACAO,D.CONTA_CONTRATO
    FROM EQTLINFO_PRD.{SCHEMA}.TAB_CADASTRO D
    WHERE EXISTS (SELECT 1 FROM FAT B WHERE B.INSTALACAO=D.INSTALACAO AND B.CONTA_CONTRATO=D.CONTA_CONTRATO)
    GROUP BY D.INSTALACAO,D.CONTA_CONTRATO HAVING COUNT(*)>1
)
UNION ALL
SELECT 'SIGLA_MUNICIPIOS: mais de uma linha por código', COUNT(*)
FROM (
    SELECT COD_MUNICIPIO FROM EQTLINFO_PRD.{SCHEMA}.SIGLA_MUNICIPIOS
    GROUP BY COD_MUNICIPIO HAVING COUNT(*)>1
)
UNION ALL
SELECT 'FOTO_CADASTRO: mais de uma linha por instalação/mês de referência usado', COUNT(*)
FROM (
    SELECT D.INSTALACAO,TO_VARCHAR(D.MES_COMPETENCIA,'YYYYMM') AS MES_FOTO
    FROM EQTLINFO_PRD.{SCHEMA}.FOTO_CADASTRO D
    WHERE EXISTS (SELECT 1 FROM CONSUMO A WHERE A.INSTALACAO=D.INSTALACAO
                  AND A.MES_REFERENCIA=TO_VARCHAR(D.MES_COMPETENCIA,'YYYYMM'))
    GROUP BY D.INSTALACAO,TO_VARCHAR(D.MES_COMPETENCIA,'YYYYMM') HAVING COUNT(*)>1
)
UNION ALL
SELECT 'FL_ISOLADO: mais de uma vigência ativa por cabeçalho de consumo próprio', COUNT(*)
FROM (
    SELECT A.MES_COMPETENCIA,A.DOCUMENTO_IMPRESSAO,A.DOCUMENTO_CALCULO
    FROM CONSUMO A
    JOIN EQTLINFO_PRD.{SCHEMA}.TAB_OPERANDOS_MEDICAO C ON A.INSTALACAO=C.INSTALACAO
      AND TO_DATE(A.MES_REFERENCIA||'01','YYYYMMDD')
          BETWEEN TO_DATE(C.DATA_DE,'YYYYMMDD') AND TO_DATE(C.DATA_ATE,'YYYYMMDD')
      AND C.OPERANDO='FL_ISOLADO'
    GROUP BY A.MES_COMPETENCIA,A.DOCUMENTO_IMPRESSAO,A.DOCUMENTO_CALCULO HAVING COUNT(*)>1
)
UNION ALL
SELECT 'FINPAD_NOTAS: mais de uma linha por mandante/nota/documento', COUNT(*)
FROM (
    SELECT MANDANTE,NOTA,NUMERO_DOCUMENTO
    FROM EQTLINFO_PRD.{SCHEMA}.FINPAD_NOTAS
    WHERE TIPO_DOC_VENDAS='ZPAD' AND TO_CHAR(DATA_ENTRADA,'YYYYMM') BETWEEN '{MES_INICIO}' AND '{MES_FIM}'
    GROUP BY MANDANTE,NOTA,NUMERO_DOCUMENTO HAVING COUNT(*)>1
)
UNION ALL
SELECT 'FINPAD_NOTAS: documento financeiro encontra mais de uma nota/linha (join DOC x SUB)', COUNT(*)
FROM (
    SELECT NUMERO_DOCUMENTO
    FROM EQTLINFO_PRD.{SCHEMA}.FINPAD_NOTAS
    WHERE TIPO_DOC_VENDAS='ZPAD' AND TO_CHAR(DATA_ENTRADA,'YYYYMM') BETWEEN '{MES_INICIO}' AND '{MES_FIM}'
    GROUP BY NUMERO_DOCUMENTO HAVING COUNT(*)>1
);
