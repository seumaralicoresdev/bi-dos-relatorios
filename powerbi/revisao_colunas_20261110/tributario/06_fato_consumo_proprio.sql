WITH ORIGEM AS (
WITH BASE_ICMS AS (
    SELECT
        DOCUMENTO_IMPRESSAO,
        DOCUMENTO_CALCULO,
        SUM(BASE_IMPOSTO) AS SUM_BASE_IMPOSTO
    FROM EQTLINFO_PRD.{SCHEMA}.ITENS_FATURAMENTO
    WHERE TIPO_IMPOSTO = 'MW2'
      AND FLAG = 'R'
    GROUP BY
        DOCUMENTO_IMPRESSAO,
        DOCUMENTO_CALCULO
)
SELECT
    B.EMPRESA,
    COALESCE(B.CNPJ, COALESCE(E.CNPJ, E.CPF)) AS CNPJ_OU_CPF,
    COALESCE(B.NOME, E.NOME) AS RAZAO_SOCIAL,
    A.INSTALACAO,
    A.CONTA_CONTRATO,
    SUBSTR(A.FATURA,8) AS NUMERO_FATURA,
    COALESCE(A.PARCEIRO_NEGOCIO,E.PARCEIRO_NEGOCIO) AS PARCEIRO_NEGOCIO,
    A.TIPO_CALCULO,
    CASE
        WHEN A.TIPO_CALCULO = 'CP' THEN 'PERIÓDICA'
        WHEN A.TIPO_CALCULO = 'CF' THEN 'DESLIGAMENTO'
    END AS TIPO_FATURAMENTO,
    CASE
        WHEN A.TIPO_CALCULO = 'CP' THEN '01'
        WHEN A.TIPO_CALCULO = 'CF' THEN '03'
    END AS COD_TP_FAT,
    A.FATURA,
    A.CONTRATO,
    A.DOCUMENTO_IMPRESSAO,
    CASE
        WHEN C.OPERANDO = 'FL_ISOLADO'
        THEN 'SISTEMA ISOLADO'
        ELSE 'SISTEMA INTERLIGADO'
    END AS TIPO_SISTEMA,
    B.SUBCLASSE AS CLASSE_CONSUMO,
    B.REGIONAL,
    B.DISTRITAL,
    B.SECCIONAL,
    B.MUNICIPIO,
    B.LOCALIDADE,
    B.ENDERECO,
    B.BAIRRO,
    B.NUMERO AS NUMERO_ENDERECO,
    B.COMPLEMENTO,
    B.COMPLEMENTO2,
    A.MES_COMPETENCIA AS COMPETENCIA,
    CASE
        WHEN A.MES_COMPETENCIA = A.MES_REFERENCIA
        THEN 'FATURA NORMAL'
        ELSE 'ESTORNO DE OUTRA REFERENCIA'
    END AS SITUACAO_DOCUMENTO,
    B.CLASSE_PRINCIPAL,
    A.TIPO_CALCULO AS CDC,
    D.SUM_BASE_IMPOSTO AS BC_ICMS,
    A.ICMS AS ICMS_TOTAL,
    A.VALOR_FATURA AS VALOR_TOTAL,
    A.CONSUMO_FATURADO
FROM EQTLINFO_PRD.{SCHEMA}.FATURAMENTO A
LEFT JOIN EQTLINFO_PRD.{SCHEMA}.FOTO_CADASTRO B
       ON A.INSTALACAO = B.INSTALACAO
      AND TO_VARCHAR(B.MES_COMPETENCIA,'YYYYMM') = A.MES_REFERENCIA
LEFT JOIN EQTLINFO_PRD.{SCHEMA}.TAB_OPERANDOS_MEDICAO C
       ON A.INSTALACAO = C.INSTALACAO
      AND TO_DATE(A.MES_REFERENCIA||'01','YYYYMMDD')
          BETWEEN TO_DATE(C.DATA_DE,'YYYYMMDD')
          AND TO_DATE(C.DATA_ATE,'YYYYMMDD')
      AND C.OPERANDO = 'FL_ISOLADO'
LEFT JOIN BASE_ICMS D
       ON A.DOCUMENTO_CALCULO = D.DOCUMENTO_CALCULO
      AND A.DOCUMENTO_IMPRESSAO = D.DOCUMENTO_IMPRESSAO
LEFT JOIN EQTLINFO_PRD.{SCHEMA}.TAB_PARCEIRO_NEGOCIO E
       ON A.PARCEIRO_NEGOCIO = E.PARCEIRO_NEGOCIO
WHERE
      A.MES_COMPETENCIA = '{MES_COMPET}'
  AND A.TIPO_CALCULO IN ('CP','CF')
  AND SUBSTR(A.SUBCLASSE,1,2) = 'CP'
  AND A.ESTORNO_PLENO IS NULL
)
SELECT '{EMP}' AS "EmpresaChave",
    TO_VARCHAR(EMPRESA) AS "EmpresaOrigem",
    TRY_TO_DATE(TO_VARCHAR(COMPETENCIA)||'01','YYYYMMDD') AS "DataCompetencia",
    TO_VARCHAR(CNPJ_OU_CPF) AS "CnpjOuCpf",
    TO_VARCHAR(RAZAO_SOCIAL) AS "RazaoSocial",
    TO_VARCHAR(INSTALACAO) AS "Instalacao",
    TO_VARCHAR(CONTA_CONTRATO) AS "ContaContrato",
    TO_VARCHAR(NUMERO_FATURA) AS "NumeroFatura",
    TO_VARCHAR(PARCEIRO_NEGOCIO) AS "ParceiroNegocio",
    TO_VARCHAR(TIPO_CALCULO) AS "TipoCalculo",
    TO_VARCHAR(TIPO_FATURAMENTO) AS "TipoFaturamento",
    TO_VARCHAR(COD_TP_FAT) AS "CodigoTipoFaturamento",
    TO_VARCHAR(FATURA) AS "Fatura",
    TO_VARCHAR(CONTRATO) AS "Contrato",
    TO_VARCHAR(DOCUMENTO_IMPRESSAO) AS "DocumentoImpressao",
    TO_VARCHAR(TIPO_SISTEMA) AS "TipoSistema",
    TO_VARCHAR(CLASSE_CONSUMO) AS "ClasseConsumo",
    TO_VARCHAR(REGIONAL) AS "Regional",
    TO_VARCHAR(DISTRITAL) AS "Distrital",
    TO_VARCHAR(SECCIONAL) AS "Seccional",
    TO_VARCHAR(MUNICIPIO) AS "Municipio",
    TO_VARCHAR(LOCALIDADE) AS "Localidade",
    TO_VARCHAR(ENDERECO) AS "Endereco",
    TO_VARCHAR(BAIRRO) AS "Bairro",
    TO_VARCHAR(NUMERO_ENDERECO) AS "NumeroEndereco",
    TO_VARCHAR(COMPLEMENTO) AS "Complemento",
    TO_VARCHAR(COMPLEMENTO2) AS "Complemento2",
    TO_VARCHAR(SITUACAO_DOCUMENTO) AS "SituacaoDocumento",
    TO_VARCHAR(CLASSE_PRINCIPAL) AS "ClassePrincipal",
    TO_VARCHAR(CDC) AS "CDC",
    ICMS_TOTAL AS "ICMS",
    BC_ICMS AS "BaseICMS",
    VALOR_TOTAL AS "ValorFatura",
    CONSUMO_FATURADO AS "ConsumoOrigem"
FROM ORIGEM;
