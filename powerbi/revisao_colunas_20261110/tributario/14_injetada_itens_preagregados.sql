-- Validar unicidade dos joins e reconciliar totais antes de substituir a consulta.
-- Mensal MES. Os 3 campos NF3E permanecem NULL, como no SQL de automação.
-- Não considerar nomes presentes como evidência de dados disponíveis.
-- RASCUNHO: evita multiplicação da receita pela autojunção com ZPGAT.
-- Ampliação inclui cliente/endereço. Montante de ICMS não é projetado no original.
-- Comparar a nova definição de TOTAL_INJET (soma dos ZPGAT) com a regra de negócio antes de usar.
WITH ITENS AS (
 SELECT MES_COMPETENCIA,DOCUMENTO_IMPRESSAO,DOCUMENTO_CALCULO,
        SUM(CASE WHEN ITEM_DOCUMENTO IN ('ZEGAT','ZEGFP','ZEGIT','ZEGNP','ZEGRV')
                 THEN CONSUMO END) AS CONSUMO,
        SUM(CASE WHEN ITEM_DOCUMENTO IN ('ZEGAT','ZEGFP','ZEGIT','ZEGNP','ZEGRV',
                                         'ZTGAT','ZTGFP','ZTGIT','ZTGNP','ZTGRV')
                 THEN RECEITA END) AS RECEITA
 FROM EQTLINFO_PRD.{SCHEMA}.ITENS_FATURAMENTO
 WHERE MES_COMPETENCIA='{MES}' AND OPERACAO IN ('0100','0200','0300')
   AND SUB_OPERACAO IN ('0016','0026','0010')
 GROUP BY MES_COMPETENCIA,DOCUMENTO_IMPRESSAO,DOCUMENTO_CALCULO
), INJETADA AS (
 SELECT MES_COMPETENCIA,DOCUMENTO_IMPRESSAO,DOCUMENTO_CALCULO,SUM(CONSUMO) AS TOTAL_INJET
 FROM EQTLINFO_PRD.{SCHEMA}.ITENS_FATURAMENTO
 WHERE MES_COMPETENCIA='{MES}' AND ITEM_DOCUMENTO='ZPGAT'
 GROUP BY MES_COMPETENCIA,DOCUMENTO_IMPRESSAO,DOCUMENTO_CALCULO
)
SELECT '{EMP}' AS "EmpresaChave",TO_DATE(I.MES_COMPETENCIA||'01','YYYYMMDD') AS "DataCompetencia",
       TO_VARCHAR(I.DOCUMENTO_IMPRESSAO) AS "DocumentoImpressao",
       TO_VARCHAR(I.DOCUMENTO_CALCULO) AS "DocumentoCalculo",
       I.RECEITA AS "ValorItensAssinado", I.CONSUMO AS "ConsumoOrigem",
       Z.TOTAL_INJET AS "TotalInjetadoOrigem",
       TO_VARCHAR(B.MES_REFERENCIA) AS "MesReferencia",
       TRY_TO_DATE(TO_VARCHAR(B.MES_REFERENCIA)||'01','YYYYMMDD') AS "DataReferencia",
       CAST(NULL AS DATE) AS "DataEmissao",
       CAST(NULL AS VARCHAR) AS "NumeroNF3e",
       CAST(NULL AS VARCHAR) AS "ChaveAcesso",
       C.NOME AS "Nome",
       D.ENDERECO || ', ' || D.NUMERO || ', ' || D.BAIRRO || ', ' || D.MUNICIPIO || ', ' || D.CEP AS "Endereco",
       TO_VARCHAR(NVL(C.CPF,C.CNPJ)) AS "CpfCnpj",
       TO_VARCHAR(C.INSCRICAO_ESTADUAL) AS "InscricaoEstadual",
       TO_VARCHAR(B.INSTALACAO) AS "Instalacao"
FROM ITENS I LEFT JOIN INJETADA Z
 ON I.MES_COMPETENCIA=Z.MES_COMPETENCIA AND I.DOCUMENTO_IMPRESSAO=Z.DOCUMENTO_IMPRESSAO
 AND I.DOCUMENTO_CALCULO=Z.DOCUMENTO_CALCULO
LEFT JOIN EQTLINFO_PRD.{SCHEMA}.FATURAMENTO B
  ON I.MES_COMPETENCIA=B.MES_COMPETENCIA
 AND I.DOCUMENTO_IMPRESSAO=B.DOCUMENTO_IMPRESSAO
 AND I.DOCUMENTO_CALCULO=B.DOCUMENTO_CALCULO
LEFT JOIN EQTLINFO_PRD.{SCHEMA}.TAB_PARCEIRO_NEGOCIO C
  ON B.PARCEIRO_NEGOCIO=C.PARCEIRO_NEGOCIO
LEFT JOIN EQTLINFO_PRD.{SCHEMA}.TAB_CADASTRO D
  ON B.INSTALACAO=D.INSTALACAO;
