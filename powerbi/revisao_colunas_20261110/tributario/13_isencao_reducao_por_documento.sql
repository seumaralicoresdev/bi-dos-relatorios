-- Validar unicidade dos joins e reconciliar totais antes de substituir a consulta.
-- Intervalo inclusivo; mantém grão documento de impressão + cálculo + município.
-- ICMS e ValorFatura estão em 13b_isencao_cabecalho.sql; não somar cabeçalho por município.
WITH REDUCOES AS (
    SELECT MES_COMPETENCIA, DOCUMENTO_IMPRESSAO, DOCUMENTO_CALCULO,
           SUBSTR(DOMICILIO_FISCAL,4,7) AS MUNICIPIO_ORIGEM, SUM(RECEITA) AS REDUCAO
    FROM EQTLINFO_PRD.{SCHEMA}.ITENS_FATURAMENTO
    WHERE OPERACAO = '0153'
      AND MES_COMPETENCIA BETWEEN '{MES_INICIO}' AND '{MES_FIM}'
    GROUP BY MES_COMPETENCIA, DOCUMENTO_IMPRESSAO, DOCUMENTO_CALCULO,
             SUBSTR(DOMICILIO_FISCAL,4,7)
)
SELECT '{EMP}' AS "EmpresaChave",
       TO_DATE(R.MES_COMPETENCIA||'01','YYYYMMDD') AS "DataCompetencia",
       TO_VARCHAR(R.DOCUMENTO_IMPRESSAO) AS "DocumentoImpressao",
       TO_VARCHAR(R.DOCUMENTO_CALCULO) AS "DocumentoCalculo",
       R.MUNICIPIO_ORIGEM AS "MunicipioOrigem", R.REDUCAO AS "ReducaoAssinada",
       TO_VARCHAR(C.MES_REFERENCIA) AS "MesReferencia",
       TRY_TO_DATE(TO_VARCHAR(C.MES_REFERENCIA)||'01','YYYYMMDD') AS "DataReferencia",
       TO_VARCHAR(M.COD_MUNICIPIO) AS "Municipio",
       TO_VARCHAR(C.INSTALACAO) AS "Instalacao", TO_VARCHAR(C.CONTA_CONTRATO) AS "ContaContrato",
       D.NOME AS "Nome", TO_VARCHAR(D.CPF) AS "CPF", TO_VARCHAR(D.CNPJ) AS "CNPJ",
       C.GRUPO AS "Grupo", C.CATEGORIA_TARIFA AS "Tarifa",
       CASE WHEN C.SUBCLASSE IN ('REPLN','REBXR') THEN 'RESIDENCIAL'
            WHEN C.SUBCLASSE IN ('COMER','COMOS') THEN 'COMERCIAL' ELSE 'OUTROS' END AS "Classe"
FROM REDUCOES R
LEFT JOIN EQTLINFO_PRD.{SCHEMA}.FATURAMENTO C
  ON R.MES_COMPETENCIA=C.MES_COMPETENCIA
 AND R.DOCUMENTO_IMPRESSAO=C.DOCUMENTO_IMPRESSAO
 AND R.DOCUMENTO_CALCULO=C.DOCUMENTO_CALCULO
LEFT JOIN EQTLINFO_PRD.{SCHEMA}.TAB_CADASTRO D
  ON C.INSTALACAO=D.INSTALACAO AND C.CONTA_CONTRATO=D.CONTA_CONTRATO
LEFT JOIN EQTLINFO_PRD.{SCHEMA}.SIGLA_MUNICIPIOS M
  ON R.MUNICIPIO_ORIGEM=M.COD_MUNICIPIO;
