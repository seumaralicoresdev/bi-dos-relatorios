-- Piloto de leitura para Snowflake. Homologar totais e desempenho antes de substituir a fato atual.
-- Preserva a granularidade intermediária e as exclusões do SQL legado.
-- Um intervalo de meses é consultado por empresa; os identificadores não saem no resumo.
WITH ITENS AS (
    SELECT
        '{EMP}' AS EMPRESA,
        A.MES_COMPETENCIA,
        A.ITEM_ORDENACAO,
        CASE WHEN A.ITEM_DOCUMENTO = 'SUBT' THEN A.ITEM_ORDENACAO
             ELSE A.ITEM_DOCUMENTO END AS ITEM_DOCUMENTO,
        MAX(MAX(A.SUB_OPERACAO)) OVER (
            PARTITION BY A.MES_COMPETENCIA, B.DOCUMENTO_IMPRESSAO, A.ITEM_ORDENACAO
        ) AS SUB_OPERACAO,
        B.CHAVE_RECONCILIACAO,
        B.INSTALACAO,
        B.CONTA_CONTRATO,
        B.CONTRATO,
        B.FATURA,
        B.CATEGORIA_TARIFA,
        B.SUBCLASSE,
        A.RECEITA,
        B.DOCUMENTO_IMPRESSAO,
        A.LINHA
    FROM EQTLINFO_PRD.{SCHEMA}.ITENS_FATURAMENTO A
    INNER JOIN EQTLINFO_PRD.{SCHEMA}.FATURAMENTO B
        ON A.DOCUMENTO_IMPRESSAO = B.DOCUMENTO_IMPRESSAO
       AND A.DOCUMENTO_CALCULO = B.DOCUMENTO_CALCULO
    WHERE A.MES_COMPETENCIA BETWEEN '{MES_INICIO}' AND '{MES_FIM}'
      AND TRY_TO_DATE(TO_VARCHAR(A.MES_COMPETENCIA) || '01', 'YYYYMMDD') IS NOT NULL
      AND (
          A.ITEM_ORDENACAO IN (
              'YBTL','Z02L','Z03L','Z12L','Z13L','Z22L','Z23L','Z32L','Z33L',
              'Z42L','Z43L','Z52L','Z53L','Z62L','Z63L','Z72L','Z73L',
              'Z82L','Z83L','Z92L','Z93L','ZBCL','ZBGL','ZBLP','ZBLS','ZBSL','ZBTL'
          ) OR A.ITEM_ORDENACAO LIKE 'ZL%'
      )
      AND A.ITEM_DOCUMENTO <> 'ZBTLBR'
    GROUP BY
        A.MES_COMPETENCIA, A.ITEM_ORDENACAO,
        CASE WHEN A.ITEM_DOCUMENTO = 'SUBT' THEN A.ITEM_ORDENACAO ELSE A.ITEM_DOCUMENTO END,
        B.CHAVE_RECONCILIACAO, B.INSTALACAO, B.CONTA_CONTRATO, B.CONTRATO, B.FATURA,
        B.CATEGORIA_TARIFA, B.SUBCLASSE, A.RECEITA, B.DOCUMENTO_IMPRESSAO, A.LINHA
),
ORIGEM AS (
    SELECT
        EMPRESA, MES_COMPETENCIA, ITEM_ORDENACAO, ITEM_DOCUMENTO, SUB_OPERACAO,
        CHAVE_RECONCILIACAO, INSTALACAO, CONTA_CONTRATO, CONTRATO, FATURA,
        CATEGORIA_TARIFA, SUBCLASSE, DOCUMENTO_IMPRESSAO,
        CASE WHEN ITEM_ORDENACAO <> 'ZBTL' THEN 'X' END AS GD,
        SUM(RECEITA) AS RECEITA
    FROM ITENS
    WHERE RECEITA <> 0
      AND SUB_OPERACAO NOT IN ('0053', '0063')
    GROUP BY
        EMPRESA, MES_COMPETENCIA, ITEM_ORDENACAO, ITEM_DOCUMENTO, SUB_OPERACAO,
        CHAVE_RECONCILIACAO, INSTALACAO, CONTA_CONTRATO, CONTRATO, FATURA,
        CATEGORIA_TARIFA, SUBCLASSE, DOCUMENTO_IMPRESSAO
    HAVING SUM(RECEITA) <> 0
)
SELECT
    TO_VARCHAR(EMPRESA) AS "EmpresaChave",
    TRY_TO_DATE(TO_VARCHAR(MES_COMPETENCIA) || '01', 'YYYYMMDD') AS "DataCompetencia",
    ITEM_ORDENACAO AS "ItemOrdenacao",
    ITEM_DOCUMENTO AS "ItemDocumento",
    SUB_OPERACAO AS "SubOperacao",
    GD AS "MarcadorGDOrigem",
    CATEGORIA_TARIFA AS "CategoriaTarifa",
    SUBCLASSE AS "Subclasse",
    SUM(RECEITA) AS "ValorDescontoAssinado",
    COUNT(*) AS "LinhasOrigem"
FROM ORIGEM
GROUP BY
    EMPRESA, MES_COMPETENCIA, ITEM_ORDENACAO, ITEM_DOCUMENTO,
    SUB_OPERACAO, GD, CATEGORIA_TARIFA, SUBCLASSE
